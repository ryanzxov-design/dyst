using Content.Client._Dystopia.Lobby;
using Content.Client.Message;
using Content.Client.UserInterface.Systems.EscapeMenu;
using Robust.Client;
using Robust.Client.AutoGenerated;
using Robust.Client.Console;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client.Lobby.UI
{
    // Dystopia: лобби переделано в терминал Городской сети (LobbyGui.xaml, Content.Client/_Dystopia/Lobby).
    // Настройка персонажа открывается на весь экран вместо терминала; ванильные элементы перекрашиваются под тему.
    [GenerateTypedNameReferences]
    public sealed partial class LobbyGui : UIScreen
    {
        [Dependency] private IClientConsoleHost _consoleHost = default!;
        [Dependency] private IBaseClient _baseClient = default!;

        private DystopiaLobbyThemeController? _theme;
        private int _themeVersion = -1;

        public LobbyGui()
        {
            RobustXamlLoader.Load(this);
            IoCManager.InjectDependencies(this);
            SetAnchorPreset(DefaultState, LayoutPreset.Wide);
            SetAnchorPreset(Background, LayoutPreset.Wide);
            SetAnchorPreset(CharacterSetupState, LayoutPreset.Wide);
            Background.Modulate = Color.FromHex("#404040");
            DefaultState.Content = MainContainer;

            LobbySong.SetMarkup(Loc.GetString("lobby-state-song-no-song-text"));

            LeaveButton.OnPressed += _ => _consoleHost.ExecuteCommand("disconnect");
            OptionsButton.OnPressed += _ => UserInterfaceManager.GetUIController<OptionsUIController>().ToggleWindow();

            // в шапке — само имя сервера (у ванильной надписи впереди «Лобби:»)
            HeadServer.Getter = () => (_baseClient.GameInfo?.ServerName ?? string.Empty).ToUpperInvariant();
            HeadClock.Getter = () => $"{Term.Text("clock")} {DateTime.Now:HH:mm}";

            // чат — тёмная подложка, текст в цвет люминофора
            Chat.ChatWindowPanel.PanelOverride = new StyleBoxFlat { BackgroundColor = Color.Black.WithAlpha(0.35f) };
            Chat.Monochrome = true;

            // строка ввода чата: без серых плашек — рамки и текст цветом темы (через Modulate)
            var line = new StyleBoxFlat
            {
                BackgroundColor = Color.Transparent,
                BorderColor = Color.White.WithAlpha(0.45f),
                BorderThickness = new Thickness(0f, 1f, 0f, 0f),
                ContentMarginLeftOverride = 6f,
            };
            var boxed = new StyleBoxFlat
            {
                BackgroundColor = Color.Transparent,
                BorderColor = Color.White.WithAlpha(0.7f),
                BorderThickness = new Thickness(1f),
                ContentMarginLeftOverride = 6f,
                ContentMarginRightOverride = 6f,
            };
            Chat.ChatInput.PanelOverride = line;
            Chat.ChatInput.Input.StyleBoxOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.Transparent,
                ContentMarginLeftOverride = 6f,
            };
            Chat.ChatInput.ChannelSelector.StyleBoxOverride = boxed;
            Chat.ChatInput.FilterButton.StyleBoxOverride = boxed;
        }

        private DystopiaLobbyThemeController Term => _theme ??= UserInterfaceManager.GetUIController<DystopiaLobbyThemeController>();

        protected override void FrameUpdate(FrameEventArgs args)
        {
            base.FrameUpdate(args);
            if (_themeVersion == Term.Version)
                return;

            _themeVersion = Term.Version;

            // ванильные части (чат, сведения о сервере, голосования, комментарий о времени) — оттенком темы
            var tint = Term.Fg;
            Chat.Modulate = tint;
            ServerInfo.Modulate = tint;
            VoteContainer.Modulate = tint;
            PlaytimeComment.Modulate = tint;
        }

        public void SwitchState(LobbyGuiState state)
        {
            switch (state)
            {
                case LobbyGuiState.Default:
                    DefaultState.Visible = true;
                    CharacterSetupState.Visible = false;
                    Background.Visible = false;
                    break;
                case LobbyGuiState.CharacterSetup:
                    DefaultState.Visible = false;
                    CharacterSetupState.Visible = true;
                    Background.Visible = true;
                    UserInterfaceManager.GetUIController<LobbyUIController>().ReloadCharacterSetup();
                    break;
            }
        }

        public enum LobbyGuiState : byte
        {
            /// <summary>
            ///  The default state, i.e., what's seen on launch.
            /// </summary>
            Default,
            /// <summary>
            ///  The character setup state.
            /// </summary>
            CharacterSetup
        }
    }
}
