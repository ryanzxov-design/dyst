        _organs = _entityManager.System<BodySystem>();
        _wounds = _entityManager.System<WoundSystem>();
        _solutions = _entityManager.System<SharedSolutionContainerSystem>();
        _traumas = _entityManager.System<TraumaSystem>();

        _buttons = new Dictionary<TargetBodyPart, TextureButton>
        {
            { TargetBodyPart.Head, HeadButton },
            { TargetBodyPart.Chest, ChestButton },
            { TargetBodyPart.Groin, GroinButton },
            { TargetBodyPart.LeftArm, LeftArmButton },
            { TargetBodyPart.LeftHand, LeftHandButton },
            { TargetBodyPart.RightArm, RightArmButton },
            { TargetBodyPart.RightHand, RightHandButton },
            { TargetBodyPart.LeftLeg, LeftLegButton },
            { TargetBodyPart.LeftFoot, LeftFootButton },
            { TargetBodyPart.RightLeg, RightLegButton },
            { TargetBodyPart.RightFoot, RightFootButton },
        };

        _statusLayers = new Dictionary<TargetBodyPart, TextureRect>
        {
            { TargetBodyPart.Head, StatusHead },
            { TargetBodyPart.Chest, StatusChest },
            { TargetBodyPart.Groin, StatusGroin },
            { TargetBodyPart.LeftArm, StatusLeftArm },
            { TargetBodyPart.LeftHand, StatusLeftHand },
            { TargetBodyPart.RightArm, StatusRightArm },
            { TargetBodyPart.RightHand, StatusRightHand },
            { TargetBodyPart.LeftLeg, StatusLeftLeg },
            { TargetBodyPart.LeftFoot, StatusLeftFoot },
            { TargetBodyPart.RightLeg, StatusRightLeg },
            { TargetBodyPart.RightFoot, StatusRightFoot },
        };

        foreach (var (part, button) in _buttons)
        {
            button.MouseFilter = MouseFilterMode.Stop;
            button.OnMouseEntered += _ => { _hovered = part; UpdateDollHighlight(); };
            button.OnMouseExited += _ => { if (_hovered == part) _hovered = null; UpdateDollHighlight(); };
            button.OnPressed += _ =>
            {
                _selected = part;
                _mode = Mode.Body;
                Refresh();
            };
        }

        ReturnButton.OnPressed += _ =>
        {
            _selected = null;
            Refresh();
        };

        BodyButton.OnPressed += _ => SetMode(Mode.Body);
        OrgansButton.OnPressed += _ => SetMode(Mode.Organs);
        ChemicalsButton.OnPressed += _ => SetMode(Mode.Chemicals);
    }

    private void SetMode(Mode mode)
    {
        _mode = mode;
        if (mode != Mode.Body)
            _selected = null;
        Refresh();
    }

    public void Populate(HealthAnalyzerUiState state)
    {
        var target = _entityManager.GetEntity(state.TargetEntity);
        if (target != _target)
        {
            _selected = null;
            _mode = Mode.Body;
        }

        _state = state;
        _target = target;
        Refresh();
    }

    private void Refresh()
    {
        if (_state is not { } state || _target is not { } target || !_entityManager.EntityExists(target) ||
            !_entityManager.TryGetComponent<DamageableComponent>(target, out _))
        {
            NoPatientDataText.Visible = true;
            PatientDataContainer.Visible = false;
            return;
        }

        NoPatientDataText.Visible = false;
        PatientDataContainer.Visible = true;

        SetupHeader(target, state);

        var humanoid = _entityManager.HasComponent<TargetingComponent>(target);
        PartView.Visible = humanoid;
        StatusDoll.Visible = humanoid && SpriteViewAllowed(state);
        SpriteView.Visible = !humanoid && SpriteViewAllowed(state);
        NoDataTex.Visible = !SpriteViewAllowed(state);
        if (humanoid)
            UpdateStatusDoll(target);
        OrgansButton.Disabled = !humanoid;
        BodyButton.Pressed = _mode == Mode.Body;
        OrgansButton.Pressed = _mode == Mode.Organs;
        ChemicalsButton.Pressed = _mode == Mode.Chemicals;
        UpdateDollHighlight();

        GroupsContainer.RemoveAllChildren();
        ConditionsListContainer.RemoveAllChildren();

        switch (_mode)
        {
            case Mode.Body:
                PopulateBody(target, state);
                break;
            case Mode.Organs:
                PopulateOrgans(target);
                break;
            case Mode.Chemicals:
                PopulateChemicals(target);
                break;
        }

        if (ConditionsListContainer.ChildCount == 0)
            AddCondition(Loc.GetString("condition-none"));
    }

    /// <summary>Наведённая или выбранная часть подсвечивается на кукле.</summary>
    private void UpdateDollHighlight()
    {
        foreach (var (part, layer) in _statusLayers)
        {
            layer.Modulate = part == _hovered || part == _selected ? HighlightColor : Color.White;
        }
    }

    /// <summary>Кукла состояния: каждая часть окрашена по своему состоянию (как кукла под оповещениями).</summary>
    private void UpdateStatusDoll(EntityUid target)
    {
        foreach (var (part, severity) in _wounds.GetWoundableStatesOnBody(target))
        {
            if (!_statusLayers.TryGetValue(part, out var layer))
                continue;

            var name = part.ToString().ToLowerInvariant();
            var rsi = new SpriteSpecifier.Rsi(
                new ResPath($"/Textures/_Dystopia/Health/Interface/Targeting/Status/{name}.rsi"),
                $"{name}_{(int) severity}");
            layer.Texture = _spriteSystem.Frame0(rsi);
        }
    }

