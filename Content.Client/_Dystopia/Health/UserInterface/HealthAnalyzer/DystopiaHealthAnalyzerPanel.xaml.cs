    private void AddCondition(string text)
    {
        ConditionsListContainer.AddChild(new RichTextLabel { Text = text, Margin = new Thickness(0, 4) });
    }

    private string PartName(TargetBodyPart part)
    {
        var (type, symmetry) = _body.ConvertTargetBodyPart(part);
        return Loc.GetString($"part-status-part-{type}-{symmetry}");
    }

    private static string GetStatus(MobState mobState) => mobState switch
    {
        MobState.Alive => Loc.GetString("health-analyzer-window-entity-alive-text"),
        MobState.Critical => Loc.GetString("health-analyzer-window-entity-critical-text"),
        MobState.Dead => Loc.GetString("health-analyzer-window-entity-dead-text"),
        _ => Loc.GetString("health-analyzer-window-entity-unknown-text"),
    };

    private void DrawDiagnosticGroups(Dictionary<string, FixedPoint2> groups, Dictionary<string, FixedPoint2> damageDict)
    {
        foreach (var (groupId, amount) in groups)
        {
            if (amount == 0 || !_prototypes.TryIndex<DamageGroupPrototype>(groupId, out var group))
                continue;

            var container = new BoxContainer { Orientation = LayoutOrientation.Vertical };
            var title = new BoxContainer
            {
                Margin = new Thickness(0, 6, 0, 0),
                VerticalAlignment = VAlignment.Bottom,
                Orientation = LayoutOrientation.Horizontal,
            };
            title.AddChild(new TextureRect { SetSize = new Vector2(30, 30), Texture = GetTexture(groupId.ToLower()) });
            title.AddChild(new Label
            {
                Text = Loc.GetString("health-analyzer-window-damage-group-text",
                    ("damageGroup", group.LocalizedName), ("amount", amount)),
            });
            container.AddChild(title);

            foreach (var type in group.DamageTypes)
            {
                if (!damageDict.TryGetValue(type, out var typeAmount) || typeAmount <= 0)
                    continue;

                container.AddChild(new Label
                {
                    Text = " · " + Loc.GetString("health-analyzer-window-damage-type-text",
                        ("damageType", _prototypes.Index<DamageTypePrototype>(type).LocalizedName), ("amount", typeAmount)),
                });
            }

            GroupsContainer.AddChild(container);
        }
    }

    private Texture GetTexture(string texture)
    {
        var rsiPath = new ResPath("/Textures/Objects/Devices/health_analyzer.rsi");
        var rsiSprite = new SpriteSpecifier.Rsi(rsiPath, texture);
        var rsi = _cache.GetResource<RSIResource>(rsiSprite.RsiPath).RSI;
        if (!rsi.TryGetState(rsiSprite.RsiState, out _))
            rsiSprite = new SpriteSpecifier.Rsi(rsiPath, "unknown");

        return _spriteSystem.Frame0(rsiSprite);
    }

    private float HeavyBleeding(EntityUid target)
    {
        return _entityManager.TryGetComponent<Content.Shared._Dystopia.Health.Medical.Bleeding.WoundBleedingComponent>(target, out var bleeding)
            ? bleeding.HeavyBleeding
            : 1.5f;
    }

