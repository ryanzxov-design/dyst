    private void PopulateBody(EntityUid target, HealthAnalyzerUiState state)
    {
        var partId = _selected is { } sel ? _body.GetTargetedPartEntity(target, sel) : null;
        var isPart = _selected != null;

        ReturnButton.Visible = isPart;
        PartNameLabel.Visible = isPart;
        DamageLabelHeading.Visible = true;
        DamageLabel.Visible = true;

        var humanoid = _entityManager.HasComponent<TargetingComponent>(target);
        DamageLabelHeadingVital.Visible = humanoid;
        DamageLabelVital.Visible = humanoid;
        if (humanoid)
            DamageLabelVital.Text = VitalDamage(target).ToString();

        if (isPart)
        {
            PartNameLabel.Text = partId != null
                ? Identity.Name(partId.Value, _entityManager)
                : Loc.GetString("health-analyzer-parts-missing-name", ("part", PartName(_selected!.Value)));

            var perType = new Dictionary<string, FixedPoint2>();
            if (partId != null && _entityManager.TryGetComponent<WoundableComponent>(partId, out var woundable))
            {
                foreach (var wound in _wounds.GetWoundableWounds(partId.Value, woundable))
                {
                    if (wound.Comp.IsScar || wound.Comp.WoundVisibility == WoundVisibility.AdvancedScanner)
                        continue;

                    var type = wound.Comp.DamageType.Id;
                    perType[type] = perType.GetValueOrDefault(type) + wound.Comp.WoundSeverityPoint;
                }
            }

            DamageLabel.Text = perType.Values.Aggregate(FixedPoint2.Zero, (a, b) => a + b).ToString();
            DrawDiagnosticGroups(GroupBy(perType), perType);
        }
        else
        {
            DamageLabel.Text = _damageable.GetTotalDamage(target).ToString();
            var perType = _damageable.GetAllDamage(target).DamageDict
                .ToDictionary(kv => kv.Key.Id, kv => kv.Value);
            var groups = _damageable.GetDamagePerGroup(target)
                .OrderByDescending(d => d.Value)
                .ToDictionary(x => x.Key.Id, x => x.Value);
            DrawDiagnosticGroups(groups, perType);
        }

        // «Состояние»
        var entityName = Identity.Name(target, _entityManager);
        if (state.Unrevivable == true)
            AddCondition(Loc.GetString("condition-body-unrevivable", ("entity", entityName)));
        if (state.Bleeding == true)
            AddCondition(Loc.GetString("condition-body-bleeding", ("entity", entityName)));

        // Боль (всё тело)
        if (!isPart && _entityManager.TryGetComponent<Content.Shared._Dystopia.Health.Medical.Pain.PainComponent>(target, out var pain))
        {
            if (pain.Level != Content.Shared._Dystopia.Health.Medical.Pain.PainLevel.None)
                AddCondition(Loc.GetString($"condition-pain-{pain.Level}", ("pain", (int) pain.Pain)));
            if (pain.Suppression >= 5f)
                AddCondition(Loc.GetString("condition-pain-suppressed", ("amount", (int) pain.Suppression)));
        }

        // Зависимость и ломка
        if (!isPart && _entityManager.TryGetComponent<Content.Shared._Dystopia.Health.Medical.Addiction.AddictionComponent>(target, out var addiction))
        {
            foreach (var (group, settings) in addiction.Groups)
            {
                var stage = addiction.Stages.GetValueOrDefault(group);
                if (stage > 0)
                    AddCondition(Loc.GetString("condition-withdrawal", ("group", Loc.GetString($"addiction-group-{group}")), ("stage", stage)));
                else if (addiction.Levels.GetValueOrDefault(group) >= settings.AddictedLevel)
                    AddCondition(Loc.GetString("condition-addicted", ("group", Loc.GetString($"addiction-group-{group}"))));
            }
        }

        if (!isPart && _entityManager.TryGetComponent<Content.Shared._Dystopia.Health.Medical.Pain.ConsciousnessComponent>(target, out var consciousness)
            && consciousness.Unconscious)
            AddCondition(Loc.GetString("condition-unconscious-blood"));

        if (!humanoid)
            return;

        foreach (var (part, severity) in _wounds.GetWoundableStatesOnBody(target))
        {
            if (isPart && part != _selected)
                continue;

            if (severity == WoundableSeverity.Severed)
            {
                var (type, symmetry) = _body.ConvertTargetBodyPart(part);
                AddCondition(Loc.GetString("condition-body-trauma-Dismemberment",
                    ("targetSymmetry", symmetry != BodyPartSymmetry.None
                        ? Loc.GetString($"condition-target-symmetry-{symmetry}") + " "
                        : ""),
                    ("targetType", Loc.GetString($"condition-target-type-{type}"))));
                continue;
            }

            if (severity >= WoundableSeverity.Critical)
                AddCondition(Loc.GetString($"condition-body-part-{severity}", ("woundable", PartName(part))));

            // Травмы части: кость, органы, вены, нервы
            if (_body.GetTargetedPartEntity(target, part) is not { } traumaPart)
                continue;

            var bone = _traumas.GetBoneSeverity(traumaPart, effective: false);
            if (bone != BoneSeverity.Normal)
                AddCondition(Loc.GetString($"condition-body-trauma-BoneDamage-{bone}", ("woundable", PartName(part))));
            if (_entityManager.TryGetComponent<Content.Shared._Dystopia.Health.Medical.Pain.LocalAnesthesiaComponent>(traumaPart, out var local)
                && IoCManager.Resolve<Robust.Shared.Timing.IGameTiming>().CurTime < local.Until)
                AddCondition(Loc.GetString("condition-local-anesthesia", ("woundable", PartName(part))));
            if (_entityManager.HasComponent<BoneSplintedComponent>(traumaPart))
                AddCondition(Loc.GetString("condition-body-splinted", ("woundable", PartName(part))));

            // Кровотечение, повязки, жгут
            var bleeding = 0f;
            var bandaged = false;
            var packed = false;
            foreach (var wound in _wounds.GetWoundableWounds(traumaPart))
            {
                if (!_entityManager.TryGetComponent<Content.Shared._Dystopia.Health.Medical.Bleeding.BleedInflicterComponent>(wound, out var bleed)
                    || !bleed.IsBleeding)
                    continue;

                if (bleed.Bandaged)
                    bandaged = true;
                else
                    bleeding += bleed.BleedingAmount;

                if (!bleed.Bandaged && bleed.PackedFactor < 1f)
                    packed = true;
            }

            if (bleeding > 0)
                AddCondition(Loc.GetString(bleeding >= HeavyBleeding(target) ? "condition-part-bleeding-heavy" : "condition-part-bleeding",
                    ("woundable", PartName(part))));
            if (packed)
                AddCondition(Loc.GetString("condition-part-packed", ("woundable", PartName(part))));
            else if (bandaged)
                AddCondition(Loc.GetString("condition-body-bandaged", ("woundable", PartName(part))));

            if (_entityManager.TryGetComponent<Content.Shared._Dystopia.Health.Medical.Bleeding.TourniquetAppliedComponent>(traumaPart, out var tourniquet))
            {
                var minutes = (int) (IoCManager.Resolve<Robust.Shared.Timing.IGameTiming>().CurTime - tourniquet.AppliedAt).TotalMinutes;
                AddCondition(Loc.GetString("condition-body-tourniquet", ("woundable", PartName(part)), ("minutes", minutes)));
            }

            var reported = new HashSet<string>();
            foreach (var trauma in _traumas.GetWoundableTraumas(traumaPart))
            {
                var type = trauma.Comp.TraumaType.Id;
                if (type == TraumaSystem.OrganDamage.Id && trauma.Comp.TraumaTarget is { } organ && _entityManager.EntityExists(organ))
                {
                    if (reported.Add($"{type}:{organ}"))
                        AddCondition(Loc.GetString("condition-body-trauma-OrganDamage",
                            ("woundable", PartName(part)), ("organ", Identity.Name(organ, _entityManager))));
                }
                else if ((type == TraumaSystem.VeinsDamage.Id || type == TraumaSystem.NerveDamage.Id) && reported.Add(type))
                {
                    AddCondition(Loc.GetString($"condition-body-trauma-{type}", ("woundable", PartName(part))));
                }
            }
        }
    }

    private FixedPoint2 VitalDamage(EntityUid target)
    {
        var total = FixedPoint2.Zero;
        foreach (var part in new[] { TargetBodyPart.Head, TargetBodyPart.Chest, TargetBodyPart.Groin })
        {
            if (_body.GetTargetedPartEntity(target, part) is { } partId &&
                _entityManager.TryGetComponent<WoundableComponent>(partId, out var woundable))
            {
                total += _wounds.GetWoundableSeverityPoint(partId, woundable);
            }
        }

        return total;
    }

    private Dictionary<string, FixedPoint2> GroupBy(Dictionary<string, FixedPoint2> perType)
    {
        var groups = new Dictionary<string, FixedPoint2>();
        foreach (var (type, value) in perType)
        {
            if (_wounds.GetDamageGroupByType(type) is not { } group)
                continue;
            groups[group.ID] = groups.GetValueOrDefault(group.ID) + value;
        }

        return groups.OrderByDescending(g => g.Value).ToDictionary(g => g.Key, g => g.Value);
    }

    // ===================== Органы =====================

    private void PopulateOrgans(EntityUid target)
    {
        ReturnButton.Visible = false;
        PartNameLabel.Visible = false;
        DamageLabelHeading.Visible = false;
        DamageLabel.Visible = false;
        DamageLabelHeadingVital.Visible = false;
        DamageLabelVital.Visible = false;

        foreach (var (organ, _) in _body.GetBodyOrgans(target))
        {
            var organName = Identity.Name(organ, _entityManager);

            var capacity = 100;
            var severity = OrganSeverity.Normal;
            if (_entityManager.TryGetComponent<OrganIntegrityComponent>(organ, out var integrity) && integrity.IntegrityCap > 0)
            {
                capacity = (int) Math.Round((integrity.Integrity / integrity.IntegrityCap * 100).Float());
                severity = integrity.Severity;
            }

            GroupsContainer.AddChild(new Label
            {
                Text = Loc.GetString("group-organ-status", ("organ", organName), ("capacity", capacity)),
                Margin = new Thickness(0, 4, 0, 0),
            });

            if (_entityManager.HasComponent<RottingComponent>(organ))
                AddCondition(Loc.GetString("condition-organ-rotting", ("organ", organName)));

            AddCondition(Loc.GetString($"condition-organ-damage-{severity}", ("organ", organName)));
        }
    }

    // ===================== Химикаты =====================

    private void PopulateChemicals(EntityUid target)
    {
        ReturnButton.Visible = false;
        PartNameLabel.Visible = false;
        DamageLabelHeading.Visible = false;
        DamageLabel.Visible = false;
        DamageLabelHeadingVital.Visible = false;
        DamageLabelVital.Visible = false;

        var owners = new List<EntityUid> { target };
        foreach (var organ in _organs.EnumerateOrgans<Content.Shared.Body.OrganComponent>(target))
        {
            owners.Add(organ.Owner);
        }

        foreach (var owner in owners)
        {
            foreach (var (name, solution) in _solutions.EnumerateSolutions(owner))
            {
                // «food» — это сами органы как мясо (их можно съесть), а не химикаты в пациенте
                if (name != null && HiddenSolutions.Contains(name))
                    continue;

                var contents = solution.Comp.Solution.Contents;
                if (contents.Count == 0)
                    continue;

                var title = name == null
                    ? Loc.GetString("group-solution-unknown")
                    : Loc.TryGetString($"group-solution-name-{name}", out var localized) ? localized : name;

                GroupsContainer.AddChild(new Label
                {
                    Text = Loc.GetString("group-solution-name", ("solution", title)),
                    Margin = new Thickness(0, 6, 0, 0),
                    StyleClasses = { "LabelHeading" },
                });

                foreach (var reagent in contents)
                {
                    string reagentName = _prototypes.TryIndex<ReagentPrototype>(reagent.Reagent.Prototype, out var proto)
                        ? proto.LocalizedName
                        : reagent.Reagent.Prototype.Id;

                    GroupsContainer.AddChild(new Label
                    {
                        Text = " · " + Loc.GetString("group-solution-contents", ("reagent", reagentName), ("quantity", reagent.Quantity)),
                    });
                }
            }
        }
    }

